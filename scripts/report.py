"""Build RESULTS.md from the saved results (no API calls).

    .venv/bin/python scripts/report.py test
"""
from __future__ import annotations

import json
import sqlite3
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from scripts.run_adaptive import CASCADE, ROUNDS, TARGETS  # noqa: E402
from witness.defense import (ENSEMBLES, PAIR_GROUPS, SINGLES, arms, by_doc, decide, group_mean_phi,  # noqa: E402
                             joint_fooling, wilson)
from witness.providers import LEDGER, ROOT  # noqa: E402


def load(name):
    p = ROOT / "results" / name
    return [json.loads(x) for x in p.read_text().splitlines()] if p.exists() else []


def pct(k, n):
    return f"{k}/{n} ({100 * k / n:.0f}%)" if n else "-"


def ci(k, n):
    lo, hi = wilson(k, n)
    return f"[{100 * lo:.0f}–{100 * hi:.0f}%]"


def main(split):
    L = []
    w = L.append
    static = load(f"{split}_static.jsonl")
    adapt = load(f"{split}_adaptive.jsonl")
    full16 = load(f"{split}_adaptive_full16.jsonl")
    # the pre-registered 9-witness deferred evaluation = the main-campaign part of the 16-witness evaluation
    full = load(f"{split}_adaptive_full.jsonl") or [r for r in full16 if r["witness"] in SINGLES and
                                                    r["family"].split(":")[1] in TARGETS]
    pg2 = {r["doc"]: r["score"] for r in load(f"{split}_pg2.jsonl")}
    sdocs = by_doc(static)
    clean = [d for d in sdocs.values() if not d["attacked"]]
    attacked = [d for d in sdocs.values() if d["attacked"]]

    w(f"# Results ({split} split)\n")
    w("Generated by `scripts/report.py` from `results/`. Plan: `PREREG.md` (commit 64c7417). "
      "All counts are documents or campaigns; brackets are Wilson 95% intervals.\n")

    # ------------------------------------------------------------ static
    w("## 1. Static attacks\n")
    w(f"{len(clean)} clean and {len(attacked)} attacked documents, 9 witnesses each.\n")
    w("| witness | clean: correct | clean: flagged | attacked: fooled | attacked: flagged | invisible fam. fooled | visible fam. fooled |")
    w("|---|---|---|---|---|---|---|")
    for s in SINGLES:
        c_ok = sum(d["votes"][s]["correct"] for d in clean); c_fl = sum(d["votes"][s]["conflict"] for d in clean)
        a_f = sum(d["votes"][s]["fooled"] for d in attacked); a_fl = sum(d["votes"][s]["conflict"] for d in attacked)
        inv = [d for d in attacked if d.get("invisible")]; vis = [d for d in attacked if not d.get("invisible")]
        w(f"| {s} | {pct(c_ok, len(clean))} | {c_fl} | {pct(a_f, len(attacked))} | {a_fl} | "
          f"{pct(sum(d['votes'][s]['fooled'] for d in inv), len(inv))} | {pct(sum(d['votes'][s]['fooled'] for d in vis), len(vis))} |")
    fam = Counter((d["family"], s) for d in attacked for s in SINGLES if d["votes"][s]["fooled"])
    if fam:
        w("\nFooled reads by family: " + ", ".join(f"{f} / {s}: {n}" for (f, s), n in fam.most_common()) + ".")
    ref = Counter(r["witness"] for r in static if r["status"] == "refusal")
    unp = Counter(r["witness"] for r in static if r["status"] == "unparsed")
    w(f"\nRefusals: {dict(ref) or 'none'}. Unparsable answers: {dict(unp) or 'none'}.\n")

    w("### Arms on the static documents (H4: cost of safety on clean documents)\n")
    w("| arm | clean: correct (utility) | clean: escalated | attacked: attacker accepted | attacked: escalated |")
    w("|---|---|---|---|---|")
    for name, (ws, flag) in arms().items():
        if name in SINGLES or name.endswith("+flag") or name in ENSEMBLES:
            oc = Counter(decide(d["votes"], ws, flag, d["truth"], d["attacker"]) for d in clean)
            oa = Counter(decide(d["votes"], ws, flag, d["truth"], d["attacker"]) for d in attacked)
            w(f"| {name} | {pct(oc['correct'], len(clean))} | {pct(oc['escalate'], len(clean))} | "
              f"{pct(oa['attacker'], len(attacked))} | {pct(oa['escalate'], len(attacked))} |")
    if pg2:
        thr = 0.5
        det_a = sum(pg2.get(d["sid"] + "|" + d["family"], 0) >= thr for d in attacked)
        det_c = sum(pg2.get(d["sid"] + "|clean", 0) >= thr for d in clean)
        w(f"\n**Prompt Guard 2 (86M) detector, threshold 0.5:** flagged {pct(det_a, len(attacked))} of attacked and "
          f"{pct(det_c, len(clean))} of clean documents.")
        by_f = defaultdict(list)
        for d in attacked:
            by_f[d["family"]].append(pg2.get(d["sid"] + "|" + d["family"], 0) >= thr)
        w(" By family: " + ", ".join(f"{f} {sum(v)}/{len(v)}" for f, v in sorted(by_f.items())) + ".\n")

    # ------------------------------------------------------------ adaptive
    w("## 2. Adaptive, defence-aware attacker (H1)\n")
    camp = defaultdict(list)
    for r in adapt:
        camp[(r["sid"], r["target"])].append(r)
    w(f"Attacker GPT-5.5 (reasoning effort low), up to {ROUNDS} rounds per campaign, {len({k[0] for k in camp})} scenarios.\n")
    w("| target | campaigns won by attacker | rounds used | valid rounds | invalid rounds | attacker refusals | attacker $ |")
    w("|---|---|---|---|---|---|---|")
    for t in TARGETS:
        cs = [v for k, v in camp.items() if k[1] == t]
        won = [c for c in cs if any(r.get("outcome") == "attacker" for r in c)]
        rounds = sum(len(c) for c in cs); valid = sum(r["valid"] for c in cs for r in c)
        refus = sum(r.get("attacker_stop") == "refusal" or "can’t help" in (r.get("strategy") or "") or
                    "can't help" in (r.get("strategy") or "") for c in cs for r in c)
        usd = sum(r["attacker_usd"] for c in cs for r in c)
        w(f"| {t} | {pct(len(won), len(cs))} {ci(len(won), len(cs))} | {rounds} | {valid} | {rounds - valid} | {refus} | ${usd:.2f} |")
        for c in won:
            r = next(x for x in c if x.get("outcome") == "attacker")
            w(f"|  ↳ won: {r['sid']} in round {r['round']} | | | | | | |")
    outcomes = Counter((r["target"], r.get("outcome") or "invalid") for r in adapt)
    w("\nRound outcomes: " + ", ".join(f"{t} {o}: {n}" for (t, o), n in sorted(outcomes.items())) + ".")
    probs = Counter((r.get("problem") or "").split(" (")[0].split(":")[0] for r in adapt if not r["valid"])
    if probs:
        w(" Invalid-round reasons: " + ", ".join(f"{p}: {n}" for p, n in probs.most_common()) + ".")
    reached = Counter(len(r.get("asked", [])) for r in adapt if r["target"] == "T2_all_flag" and r["valid"])
    if reached:
        w(f"\nT2 cascade depth (witnesses asked before it stopped): {dict(sorted(reached.items()))}.")
    stop_at = Counter(r["asked"][-1] for r in adapt if r["target"] == "T2_all_flag" and r["valid"] and r.get("outcome") == "blocked")
    if stop_at:
        w(f" Witness that stopped it: {dict(stop_at.most_common())}.\n")

    # ------------------------------------------------------------ correlation
    fdocs = list(by_doc(full).values())
    w("## 3. Do witnesses fail together? (H2, H3)\n")
    pool = attacked + fdocs
    w(f"Pool: {len(attacked)} static attacked documents + {len(fdocs)} valid adaptive snippets, each read by all 9 witnesses.\n")
    w("| witness | fooled (pool) | fooled (adaptive snippets) |")
    w("|---|---|---|")
    for s in SINGLES:
        w(f"| {s} | {pct(sum(d['votes'][s]['fooled'] for d in pool), len(pool))} | "
          f"{pct(sum(d['votes'][s]['fooled'] for d in fdocs), len(fdocs))} |")
    w("\n**H2: mean phi of the fooled indicators by pair group** (cluster bootstrap over scenarios). "
      "A pair where either witness was never fooled has undefined phi and is skipped.\n")
    w("| group | pairs | mean phi | 95% CI |")
    w("|---|---|---|---|")
    for g, pairs in PAIR_GROUPS.items():
        m = group_mean_phi(pool, pairs)
        defined = [p for p in pairs if joint_fooling(pool, *p)["phi"] is not None]
        mp = "undefined" if m["mean_phi"] is None else f"{m['mean_phi']:.2f}"
        c = "-" if m["ci95"][0] is None else f"[{m['ci95'][0]:.2f}, {m['ci95'][1]:.2f}]"
        w(f"| {g} | {len(defined)}/{len(pairs)} defined | {mp} | {c} |")
    w("\nAll pairs with at least one joint observation:\n")
    w("| pair | P(a fooled) | P(b fooled) | P(both) | P(b|a) | lift | phi |")
    w("|---|---|---|---|---|---|---|")
    for i, a in enumerate(SINGLES):
        for b in SINGLES[i + 1:]:
            j = joint_fooling(pool, a, b)
            if j["pa"] > 0 and j["pb"] > 0:
                f = lambda x: "-" if x is None else f"{x:.2f}"  # noqa: E731
                w(f"| {a} – {b} | {j['pa']:.3f} | {j['pb']:.3f} | {j['pab']:.3f} | {f(j['p_b_given_a'])} | {f(j['lift'])} | {f(j['phi'])} |")

    w("\n**H3: transfer of adaptive snippets that fooled opus_raw**\n")
    src = [d for d in fdocs if d["votes"]["opus_raw"]["fooled"]]
    if src:
        w(f"{len(src)} snippets fooled opus_raw. Share that also fooled each other witness:\n")
        for s in SINGLES:
            if s != "opus_raw":
                w(f"- {s}: {pct(sum(d['votes'][s]['fooled'] for d in src), len(src))}")
    else:
        w("No adaptive snippet fooled opus_raw, so H3 cannot be tested on opus_raw. Transfer from the most-fooled witness instead:\n")
        counts = {s: sum(d["votes"][s]["fooled"] for d in fdocs) for s in SINGLES}
        top = max(counts, key=counts.get) if fdocs else None
        if top and counts[top]:
            src = [d for d in fdocs if d["votes"][top]["fooled"]]
            w(f"{top} was fooled by {len(src)} snippets. Share that also fooled:\n")
            for s in SINGLES:
                if s != top:
                    w(f"- {s}: {pct(sum(d['votes'][s]['fooled'] for d in src), len(src))}")
    w("")

    # ------------------------------------------------------------ extension
    ext = load(f"{split}_adaptive_ext.jsonl")
    weak_static = load(f"{split}_static_weak.jsonl")
    if ext or weak_static:
        extension_section(w, split, static, weak_static, adapt, ext, full16)

    # ------------------------------------------------------------ cost
    w("## 6. Cost (H5)\n")
    all_docs = list(sdocs.values()) + fdocs
    full_cost = sum(d["votes"][s].get("usd", 0) or 0 for d in all_docs for s in SINGLES)
    casc_cost = 0.0
    for d in all_docs:
        for s in CASCADE:
            casc_cost += d["votes"][s].get("usd", 0) or 0
            v = d["votes"][s]
            if v["value"] is None or v["conflict"] or v["value"] != d["votes"][CASCADE[0]]["value"]:
                break
    w(f"Over {len(all_docs)} documents, at the prices actually paid (batch prices for these rows): calling all 9 "
      f"witnesses cost ${full_cost:.2f}; the same decisions by early-exit cascade would have cost ${casc_cost:.2f} "
      f"({100 * casc_cost / full_cost:.0f}%). The Tamil translation is extra and is skipped whenever the cascade stops "
      f"before a Tamil witness.\n" if full_cost else "No cost data.\n")
    con = sqlite3.connect(LEDGER)
    w("Total spend (ledger, dev included):\n")
    for prov, usd, n in con.execute("select provider, sum(usd), count(*) from calls group by provider"):
        w(f"- {prov}: ${usd:.2f} over {n} calls")
    w("")
    (ROOT / "RESULTS.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


WEAK = ["qwen_raw", "haiku_raw", "nano_raw", "haiku_img", "nano_img", "haiku_ta", "nano_ta"]
STRONG_OF = {"haiku_raw": "opus_raw", "haiku_img": "opus_img", "haiku_ta": "opus_ta",
             "nano_raw": "gpt_raw", "nano_img": "gpt_img", "nano_ta": "gpt_ta"}


def extension_section(w, split, static, weak_static, adapt, ext, full16):
    from scripts.run_extension import EXT_TARGETS
    w("## 5. Extension: weak models (EXTENSION.md, commit 48b0630)\n")
    sd = by_doc(static + weak_static)
    clean = [d for d in sd.values() if not d["attacked"]]
    att = [d for d in sd.values() if d["attacked"]]
    w("### Static documents\n")
    w("| witness | clean: correct | attacked: fooled | attacked: other wrong value | attacked: flagged |")
    w("|---|---|---|---|---|")
    for s_ in WEAK:
        if all(s_ in d["votes"] for d in att):
            ow = sum(d["votes"][s_]["value"] is not None and not d["votes"][s_]["correct"] and not d["votes"][s_]["fooled"] for d in att)
            w(f"| {s_} | {pct(sum(d['votes'][s_]['correct'] for d in clean), len(clean))} | "
              f"{pct(sum(d['votes'][s_]['fooled'] for d in att), len(att))} | {ow} | {sum(d['votes'][s_]['conflict'] for d in att)} |")
    allc = adapt + ext
    camp = defaultdict(list)
    for r in allc:
        camp[(r["sid"], r["target"])].append(r)
    w("\n### E1, E2: campaigns won by the attacker\n")
    w("| target | won | 95% CI | median winning round | attacker $ |")
    w("|---|---|---|---|---|")
    for t in list(TARGETS) + list(EXT_TARGETS):
        cs = [v for k, v in camp.items() if k[1] == t]
        if not cs:
            continue
        wins = [next(r["round"] for r in c if r.get("outcome") == "attacker") for c in cs if any(r.get("outcome") == "attacker" for r in c)]
        med = sorted(wins)[len(wins) // 2] if wins else "-"
        w(f"| {t} | {len(wins)}/{len(cs)} | {ci(len(wins), len(cs))} | {med} | ${sum(r['attacker_usd'] for c in cs for r in c):.2f} |")
    fd = list(by_doc(full16).values())
    if not fd:
        w("\n(16-witness evaluation not run yet.)\n")
        return
    names = [x for x in SINGLES + WEAK if x in fd[0]["votes"]]
    w(f"\n### E4, E5: every valid snippet ({len(fd)}) read by the witnesses\n")
    w("| witness | fooled | other wrong | correct |")
    w("|---|---|---|---|")
    seen = set()
    for s_ in SINGLES + WEAK:
        if s_ in seen:
            continue
        seen.add(s_)
        ds = [d for d in fd if s_ in d["votes"]]
        if ds:
            fo = sum(d["votes"][s_]["fooled"] for d in ds)
            ow = sum(d["votes"][s_]["value"] is not None and not d["votes"][s_]["correct"] and not d["votes"][s_]["fooled"] for d in ds)
            w(f"| {s_} | {pct(fo, len(ds))} | {ow} | {pct(sum(d['votes'][s_]['correct'] for d in ds), len(ds))} |")
    w("\n**E4: transfer.** Snippets that fooled at least one weak witness; share that also fooled each strong witness:\n")
    src = [d for d in fd if any(d["votes"].get(x, {}).get("fooled") for x in WEAK)]
    for s_ in SINGLES:
        ds = [d for d in src if s_ in d["votes"]]
        if ds:
            w(f"- {s_}: {pct(sum(d['votes'][s_]['fooled'] for d in ds), len(ds))}")
    w("\n**E5: strong vs weak, same vendor and view** (fooled share on the same snippets):\n")
    for weak, strong in STRONG_OF.items():
        ds = [d for d in fd if weak in d["votes"] and strong in d["votes"]]
        if ds:
            w(f"- {strong} {pct(sum(d['votes'][strong]['fooled'] for d in ds), len(ds))} vs {weak} "
              f"{pct(sum(d['votes'][weak]['fooled'] for d in ds), len(ds))}")
    w("\n**E3: do weak witnesses fail together?** Mean phi by pair group on the snippet pool:\n")
    groups = {"same view, different vendor": [("haiku_raw", "nano_raw"), ("haiku_raw", "qwen_raw"), ("nano_raw", "qwen_raw"),
                                              ("haiku_img", "nano_img"), ("haiku_ta", "nano_ta")],
              "same vendor, different view": [("haiku_raw", "haiku_img"), ("haiku_raw", "haiku_ta"), ("haiku_img", "haiku_ta"),
                                              ("nano_raw", "nano_img"), ("nano_raw", "nano_ta"), ("nano_img", "nano_ta")]}
    w("| group | defined pairs | mean phi | 95% CI |")
    w("|---|---|---|---|")
    for g, pairs in groups.items():
        m = group_mean_phi(fd, pairs)
        dfn = sum(joint_fooling(fd, *p)["phi"] is not None for p in pairs)
        mp = "undefined" if m["mean_phi"] is None else f"{m['mean_phi']:.2f}"
        c = "-" if m["ci95"][0] is None else f"[{m['ci95'][0]:.2f}, {m['ci95'][1]:.2f}]"
        w(f"| {g} | {dfn}/{len(pairs)} | {mp} | {c} |")
    w("\nPairs:\n")
    w("| pair | P(a) | P(b) | P(both) | P(b|a) | lift | phi |")
    w("|---|---|---|---|---|---|---|")
    f = lambda x: "-" if x is None else f"{x:.2f}"  # noqa: E731
    for g, pairs in groups.items():
        for a, b in pairs:
            j = joint_fooling(fd, a, b)
            w(f"| {a} – {b} | {j['pa']:.2f} | {j['pb']:.2f} | {j['pab']:.2f} | {f(j['p_b_given_a'])} | {f(j['lift'])} | {f(j['phi'])} |")
    w("")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "test")
